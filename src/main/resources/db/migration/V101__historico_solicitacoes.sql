CREATE TABLE solicitacao_historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL REFERENCES solicitacoes(id),
    equipe_id BIGINT NOT NULL REFERENCES usuarios(id),
    status_anterior VARCHAR(24) NOT NULL,
    status_novo VARCHAR(24) NOT NULL,
    motivo VARCHAR(400),
    registrada_em TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_historico_solicitacao ON solicitacao_historico(solicitacao_id, id);
