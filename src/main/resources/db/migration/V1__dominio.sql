CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,
    papel VARCHAR(20) NOT NULL,
    telefone VARCHAR(32),
    cidade VARCHAR(120)
);

CREATE TABLE regioes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    cidade VARCHAR(120) NOT NULL,
    nivel_risco VARCHAR(20) NOT NULL,
    situacao VARCHAR(160) NOT NULL,
    descricao VARCHAR(1000),
    populacao_afetada INTEGER NOT NULL CHECK (populacao_afetada >= 0),
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    versao BIGINT NOT NULL
);

CREATE TABLE pontos_agua (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regiao_id BIGINT REFERENCES regioes(id),
    nome VARCHAR(120) NOT NULL,
    tipo VARCHAR(32) NOT NULL,
    endereco VARCHAR(240) NOT NULL,
    cidade VARCHAR(120) NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    status VARCHAR(24) NOT NULL,
    capacidade_litros INTEGER NOT NULL CHECK (capacidade_litros >= 0),
    estoque_litros INTEGER NOT NULL CHECK (estoque_litros BETWEEN 0 AND capacidade_litros),
    horario_funcionamento VARCHAR(120),
    telefone VARCHAR(32),
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    versao BIGINT NOT NULL
);

CREATE TABLE solicitacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante_id BIGINT NOT NULL REFERENCES usuarios(id),
    regiao_id BIGINT REFERENCES regioes(id),
    tipo VARCHAR(32) NOT NULL,
    descricao VARCHAR(1000) NOT NULL,
    quantidade_pessoas INTEGER NOT NULL CHECK (quantidade_pessoas > 0),
    urgencia VARCHAR(20) NOT NULL,
    grupo_vulneravel BOOLEAN NOT NULL,
    endereco VARCHAR(240) NOT NULL,
    cidade VARCHAR(120) NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    status VARCHAR(24) NOT NULL,
    prioridade INTEGER CHECK (prioridade BETWEEN 0 AND 100),
    analise_ia VARCHAR(1000),
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    excluida_em TIMESTAMP WITH TIME ZONE,
    triada_em TIMESTAMP WITH TIME ZONE,
    versao BIGINT NOT NULL
);

CREATE INDEX idx_solicitacoes_dono ON solicitacoes(solicitante_id, criada_em);
CREATE INDEX idx_solicitacoes_triagem ON solicitacoes(status, triada_em);
CREATE INDEX idx_solicitacoes_regiao ON solicitacoes(regiao_id);
CREATE INDEX idx_pontos_regiao ON pontos_agua(regiao_id);
